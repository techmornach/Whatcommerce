/** Format API ISO timestamps for the admin UI (browser locale + timezone). */
export function formatAdminDateTime(iso: string | null | undefined): string {
  if (!iso) return "—";
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return iso;
  // Do not mix `dateStyle`/`timeStyle` with `timeZoneName` — some engines throw "Invalid option".
  return new Intl.DateTimeFormat(undefined, {
    year: "numeric",
    month: "short",
    day: "numeric",
    hour: "numeric",
    minute: "2-digit",
    timeZoneName: "short",
  }).format(d);
}
